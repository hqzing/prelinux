/* PreLinux base SDK — `prelinux` single-binary multi-subcommand CLI
   (git/busybox style: one binary, subcommands, no prelinux-* in PATH). */
#define _GNU_SOURCE 1
#include <limits.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

#define PRELINUX_STANDALONE 1
#include "prelinux-translate.h"
#include "prelinux.h"

static int
cmd_root (void)
{
  char root[PATH_MAX];
  if (prelinux_resolve_root (NULL, root, sizeof (root)) != 0)
    {
      fprintf (stderr, "root: not inside an instance; pass --root or set "
		       "PRELINUX_ROOT\n");
      return 1;
    }
  printf ("%s\n", root);
  return 0;
}

static int
cmd_translate (int argc, char **argv)
{
  const char *explicit_root = NULL;
  int i = 1;
  if (i + 1 < argc && strcmp (argv[i], "--root") == 0)
    {
      explicit_root = argv[i + 1];
      i += 2;
    }
  char root[PATH_MAX];
  if (prelinux_resolve_root (explicit_root, root, sizeof (root)) != 0)
    {
      fprintf (stderr, "translate: cannot determine the instance root\n");
      return 2;
    }
  if (i >= argc)
    {
      fprintf (stderr, "usage: prelinux translate [--root DIR] PATH...\n");
      return 2;
    }
  for (; i < argc; i++)
    {
      char buf[4096];
      const char *r = __prelinux_translate_path_root (root, argv[i], buf,
						      sizeof (buf));
      if (r == NULL)
	printf ("%s -> <error: buffer too small>\n", argv[i]);
      else if (strcmp (r, argv[i]) == 0)
	printf ("%s -> %s (unchanged)\n", argv[i], r);
      else
	printf ("%s -> %s\n", argv[i], r);
    }
  return 0;
}

static int
cmd_info (int argc, char **argv)
{
  const char *explicit_root = NULL;
  if (argc > 2 && strcmp (argv[1], "--root") == 0)
    explicit_root = argv[2];
  char root[PATH_MAX];
  if (prelinux_resolve_root (explicit_root, root, sizeof (root)) != 0)
    {
      fprintf (stderr, "info: not inside an instance; pass --root DIR\n");
      return 2;
    }
  printf ("instance root: %s\n", root);
  char toml[PATH_MAX];
  snprintf (toml, sizeof (toml), "%s/.prelinux/instance.toml", root);
  FILE *f = fopen (toml, "r");
  if (f == NULL)
    {
      printf ("(no .prelinux/instance.toml)\n");
      return 0;
    }
  char line[512];
  while (fgets (line, sizeof (line), f) != NULL)
    {
      if (line[0] == '#' || line[0] == '\n')
	continue;
      fputs (line, stdout);
    }
  fclose (f);
  return 0;
}

/* Release version of the CLI, generated by the build (see Makefile):
   release builds pass the tag, local builds get 0.0.0-dev.  */
#include "prelinux-version.h"

static void
usage (void)
{
  printf ("PreLinux " PRELINUX_VERSION " — host-independent Linux userspace virtualization\n"
	  "\n"
	  "usage: prelinux <command> [args]\n"
	  "\n"
	  "commands:\n"
	  "  import <distro:ver|rootfs.tar> [dir] [--image F]\n"
	  "         create an instance from a distro rootfs tarball\n"
	  "  relocate [--root DIR] [--quiet] [--no-sign] PATH...\n"
	  "         rewrite ELF PT_INTERP/RPATH, shebangs and root slots,\n"
	  "         re-signing ELFs afterwards\n"
	  "  info [--root DIR]\n"
	  "         show instance metadata\n"
	  "  root   print the resolved instance root\n"
	  "  translate [--root DIR] PATH...\n"
	  "         show path translations (debugging)\n"
	  "  help   show this text\n"
	  "  --version  print the version\n");
}

int
main (int argc, char **argv)
{
  if (argc < 2)
    {
      usage ();
      return 2;
    }
  const char *cmd = argv[1];
  if (strcmp (cmd, "--version") == 0 || strcmp (cmd, "-V") == 0)
    {
      printf ("prelinux " PRELINUX_VERSION "\n");
      return 0;
    }
  if (strcmp (cmd, "import") == 0)
    return prelinux_cmd_import (argc - 1, argv + 1);
  if (strcmp (cmd, "relocate") == 0)
    return prelinux_cmd_relocate (argc - 1, argv + 1);
  if (strcmp (cmd, "info") == 0)
    return cmd_info (argc - 1, argv + 1);
  if (strcmp (cmd, "root") == 0)
    return cmd_root ();
  if (strcmp (cmd, "translate") == 0)
    return cmd_translate (argc - 1, argv + 1);
  usage ();
  return 2;
}
